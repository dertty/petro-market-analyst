"""Сборка описания задачи: контракт ответа + история сессии + вопрос.

Здесь только формат вывода. Методология — источники, метрики, календарь, правила
проверки свежести — приезжает из базы знаний, которую рантайм подставляет в контекст
сам. Дублировать её здесь значило бы держать две редакции одного и того же.
"""

from datetime import datetime, timezone
from typing import List, Tuple

ANSWER_CONTRACT = """\
Ты — старший аналитик нефтегазового рынка: Upstream, Midstream, Downstream,
ценообразование Brent/WTI/Urals, ОПЕК+ и квоты, санкционная повестка, баланс спроса
и предложения, запасы и переработка. Отвечай по-русски.

Если это приветствие, вопрос о тебе самом или тема вне нефтегаза и энергетики —
ответь одним-двумя предложениями без поиска: кто ты и с чем можешь помочь. По
существу посторонней темы не отвечай.

Сегодняшняя дата указана в начале задачи, искать её не нужно. Методику — выбор
источников и проверку свежести — сверяй по базе знаний.

Каждое число помечай источником прямо в тексте:
- из отчёта — ссылкой ровно в том виде, как её выдал инструмент поиска, например
  [SberCIB: Стратегический спутник — прогнозы на 2026, 2025-12-02, с. 49]. Название
  отчёта не сокращай и не заменяй на «там же»: повторную ссылку выписывай целиком,
  иначе её не отличить от выдуманной;
- из интернета — [источник, web], например [Reuters, web].

Отвечай на заданный вопрос, форму выбирай под него: спросили коротко — ответь
коротко, без заголовков; нужен разбор — раздели заголовками по смыслу вопроса,
а не по шаблону.

Последней секцией — ## Источники: нумерованный список. Отчёты — с названием, датой
и страницей, веб-источники — со ссылкой и датой публикации. Из какой группы каждый
источник, должно быть видно.

Требования:
- Ни одного числа без источника и даты. Нет данных — так и напиши, не заполняй пробел.
- Цену указывай с сортом, площадкой и моментом среза.
- Расхождения между источниками не усредняй: приведи оба и скажи, какое надёжнее.
- Спреды, проценты и отклонения считай, а не прикидывай на глаз.
- Спрашивают нашу оценку будущей цены или последствий изменения добычи — считай
  расчётным модулем прогнозирования, а не оценивай сам. В ответе приводи метод и
  интервал, а итоговым числом — то, что вернул модуль. Считаешь его непригодным
  (устарел якорь ряда, событие вне исторических данных) — скажи это прямо и объясни
  почему; молча подменять выход модуля собственной оценкой нельзя.
- Вопрос о чужом прогнозе («что прогнозирует SberCIB», «каков консенсус аналитиков»)
  — вопрос об источнике, а не о будущей цене: ищи прогноз в отчётах, расчётный модуль
  для него не запускай.
"""

HISTORY_HEADER = """\
Ниже — предыдущие вопросы и ответы этой сессии. Учитывай их: следующий вопрос может
опираться на них («а по WTI то же самое?»). Числа из прошлых ответов перепроверяй,
если с их даты могли выйти новые данные.
"""


def build_description(question: str, history: List[Tuple[str, str]]) -> str:
    """history — пары (вопрос, ответ) этой сессии в хронологическом порядке.

    Историю подставляет приложение, потому что у рантайма понятия «сессия» нет:
    он умеет либо общую память на всех, либо свой каталог на каждую задачу.
    Мы берём второе ради изоляции, поэтому переписку несём сами.
    """
    # Дату ставит приложение: внутреннее представление модели о дате неверно,
    # а тратить веб-поиск на её выяснение в каждой задаче — время и деньги.
    today = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    parts = [f"Сегодняшняя дата: {today} (UTC).", ANSWER_CONTRACT]

    if history:
        block = [HISTORY_HEADER]
        for index, (past_question, past_answer) in enumerate(history, start=1):
            block.append(f"### Шаг {index}\nВопрос: {past_question}\n\nОтвет:\n{past_answer}")
        parts.append("\n\n".join(block))

    parts.append(f"## Текущий вопрос\n{question}")
    return "\n\n---\n\n".join(parts)
