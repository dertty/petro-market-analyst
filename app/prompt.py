"""Сборка описания задачи: контракт ответа + история сессии + вопрос.

Здесь только формат вывода. Методология — источники, метрики, календарь, правила
проверки свежести — приезжает из базы знаний, которую рантайм подставляет в контекст
сам. Дублировать её здесь значило бы держать две редакции одного и того же.
"""

from typing import List, Tuple

ANSWER_CONTRACT = """\
Ты — аналитик нефтегазового рынка. Отвечай по-русски.

Прежде чем отвечать, выясни веб-поиском сегодняшнюю дату и проверь, что данные,
на которые ссылаешься, действительно последние.

Структура ответа:

## Краткий вывод
Два-три предложения: что происходит и что это значит.

## Факты
Числа с единицами измерения. У каждого — дата, к которой оно относится, и источник.

## Драйверы
Почему так. Гипотезы называй гипотезами.

## Риски
Что может изменить картину и на каком горизонте.

## Источники
Нумерованный список ссылок с датами публикации.

Требования:
- Ни одного числа без источника и даты. Нет данных — так и напиши, не заполняй пробел.
- Цену указывай с сортом, площадкой и моментом среза.
- Расхождения между источниками не усредняй: приведи оба и скажи, какое надёжнее.
- Расчёты (спреды, проценты, отклонения) выполняй на Python, а не прикидывай.

Последней строкой ответа выведи:
FINAL ANSWER: <весь отчёт в markdown>
"""

HISTORY_HEADER = """\
Ниже — предыдущие вопросы и ответы этой сессии. Учитывай их: следующий вопрос может
опираться на них («а по WTI то же самое?»). Числа из прошлых ответов перепроверяй,
если с их даты могли выйти новые данные.
"""


def build_description(question: str, history: List[Tuple[str, str]]) -> str:
    """history — пары (вопрос, ответ) этой сессии в хронологическом порядке.

    Историю подставляет приложение, потому что у рантайма понятия «сессия» нет:
    он умеет либо общую память на всех, либо свой каталог на каждую задачу.
    Мы берём второе ради изоляции, поэтому переписку несём сами.
    """
    parts = [ANSWER_CONTRACT]

    if history:
        block = [HISTORY_HEADER]
        for index, (past_question, past_answer) in enumerate(history, start=1):
            block.append(f"### Шаг {index}\nВопрос: {past_question}\n\nОтвет:\n{past_answer}")
        parts.append("\n\n".join(block))

    parts.append(f"## Текущий вопрос\n{question}")
    return "\n\n---\n\n".join(parts)
